import React, { useState, useEffect, useMemo } from 'react';
import { EngineSimulationState, LubricationComponent, OilGrade } from './types';
import { Navbar, ActiveTab } from './components/Navbar';
import { EngineSimulationCanvas } from './components/EngineSimulationCanvas';
import { ControlDeck } from './components/ControlDeck';
import { ComponentDetailModal } from './components/ComponentDetailModal';
import { LessonViewer } from './components/LessonViewer';
import { LabsViewer } from './components/LabsViewer';
import { QuizModal } from './components/QuizModal';
import { GlossaryModal } from './components/GlossaryModal';
import { COMPONENTS_DATA } from './data/componentsData';
import { LESSONS_DATA } from './data/lessonsData';
import { Activity, BookOpen, Beaker, Award, BookMarked, HelpCircle } from 'lucide-react';

export default function App() {
  const [activeTab, setActiveTab] = useState<ActiveTab>('simulation');
  const [selectedComponent, setSelectedComponent] = useState<LubricationComponent | null>(null);
  const [completedChapters, setCompletedChapters] = useState<string[]>(['ch1']);

  // Base Simulation Parameters
  const [rpm, setRpm] = useState<number>(2400);
  const [isRunning, setIsRunning] = useState<boolean>(true);
  const [temperature, setTemperature] = useState<number>(90); // °C
  const [oilGrade, setOilGrade] = useState<OilGrade>('5W-30');
  const [filterClogged, setFilterClogged] = useState<boolean>(false);
  const [oilLevel, setOilLevel] = useState<number>(75); // %

  // Physics calculation engine
  const simulationState = useMemo<EngineSimulationState>(() => {
    if (!isRunning || rpm <= 0) {
      return {
        rpm: 0,
        isRunning: false,
        temperature,
        oilGrade,
        filterClogged,
        filterClogPercent: filterClogged ? 100 : 0,
        oilLevel,
        oilPressure: 0,
        oilFlowRate: 0,
        oilViscosityCst: 10,
        bypassValveOpen: false,
        reliefValveOpen: false,
        coolerActive: false,
        oilWarningLamp: false,
        selectedComponentId: selectedComponent?.id || null,
        speedMultiplier: 1,
      };
    }

    // Kinematic Viscosity (cSt) at current temperature
    let base100cSt = 10;
    if (oilGrade === '0W-20') base100cSt = 8.5;
    if (oilGrade === '5W-30') base100cSt = 11.0;
    if (oilGrade === '10W-40') base100cSt = 14.5;
    if (oilGrade === '20W-50') base100cSt = 18.5;

    // Arrhenius temperature-viscosity relationship
    const tempFactor = Math.exp((100 - temperature) * 0.035);
    const viscosityCst = Math.max(3, Math.min(300, base100cSt * tempFactor));

    // Base pressure generated by positive displacement pump (bar)
    // RPM 800 (idle) -> ~1.6 bar, RPM 3000 -> ~3.8 bar, RPM 6000 -> ~5.8 bar
    const rpmRatio = rpm / 6000;
    let rawPressure = 0.8 + rpmRatio * 4.6;

    // Viscosity impact: cold thick oil boosts pressure; hot thin oil drops pressure
    if (temperature < 40) {
      rawPressure *= 1.35;
    } else if (temperature > 105) {
      rawPressure *= 0.75;
    }

    // Oil level impact: if level < 35%, pump starts sucking air bubbles (cavitation)
    let cavitationWarning = false;
    if (oilLevel < 35) {
      cavitationWarning = true;
      rawPressure *= (oilLevel / 50);
    }

    // Relief valve opens around 4.8 - 5.2 bar
    const reliefThreshold = 5.0;
    const reliefValveOpen = rawPressure > reliefThreshold;
    const finalPressure = Math.min(5.4, Math.max(0, rawPressure));

    // Bypass valve opens if filter is clogged OR cold thick oil creates high differential pressure
    const bypassValveOpen = filterClogged || (temperature < -10 && rpm > 1500);

    // Flow rate in L/min
    let flowRate = (rpm / 6000) * 38;
    if (oilLevel < 30) flowRate *= 0.4;

    const oilWarningLamp = isRunning && (finalPressure < 0.6 || cavitationWarning);

    return {
      rpm,
      isRunning,
      temperature,
      oilGrade,
      filterClogged,
      filterClogPercent: filterClogged ? 100 : 0,
      oilLevel,
      oilPressure: finalPressure,
      oilFlowRate: flowRate,
      oilViscosityCst: viscosityCst,
      bypassValveOpen,
      reliefValveOpen,
      coolerActive: temperature > 85,
      oilWarningLamp,
      selectedComponentId: selectedComponent?.id || null,
      speedMultiplier: 1,
    };
  }, [rpm, isRunning, temperature, oilGrade, filterClogged, oilLevel, selectedComponent]);

  // Preset Handlers
  const handleApplyPreset = (scenario: 'cold' | 'normal' | 'overheat' | 'clogged' | 'low_oil') => {
    setIsRunning(true);
    switch (scenario) {
      case 'cold':
        setTemperature(-20);
        setRpm(1200);
        setOilGrade('20W-50');
        setFilterClogged(false);
        setOilLevel(75);
        break;
      case 'normal':
        setTemperature(90);
        setRpm(2800);
        setOilGrade('5W-30');
        setFilterClogged(false);
        setOilLevel(75);
        break;
      case 'overheat':
        setTemperature(120);
        setRpm(4200);
        setOilGrade('0W-20');
        setFilterClogged(false);
        setOilLevel(60);
        break;
      case 'clogged':
        setTemperature(85);
        setRpm(2200);
        setOilGrade('5W-30');
        setFilterClogged(true);
        setOilLevel(75);
        break;
      case 'low_oil':
        setTemperature(98);
        setRpm(1500);
        setOilGrade('5W-30');
        setFilterClogged(false);
        setOilLevel(25);
        break;
    }
  };

  const handleResetSimulation = () => {
    setIsRunning(true);
    setRpm(2200);
    setTemperature(90);
    setOilGrade('5W-30');
    setFilterClogged(false);
    setOilLevel(75);
    setSelectedComponent(null);
  };

  const handleToggleCompleteChapter = (chapterId: string) => {
    setCompletedChapters((prev) =>
      prev.includes(chapterId) ? prev.filter((id) => id !== chapterId) : [...prev, chapterId]
    );
  };

  const handleJumpToSimulationComponent = (componentId: string) => {
    const comp = COMPONENTS_DATA.find((c) => c.id === componentId);
    if (comp) {
      setSelectedComponent(comp);
    }
    setActiveTab('simulation');
    window.scrollTo({ top: 0, behavior: 'smooth' });
  };

  return (
    <div className="min-h-screen bg-slate-950 text-slate-100 flex flex-col font-sans">
      {/* Strict 3-zone constitution top navigation */}
      <Navbar
        activeTab={activeTab}
        onTabChange={setActiveTab}
        onResetSimulation={handleResetSimulation}
        completedLessonsCount={completedChapters.length}
        totalLessonsCount={LESSONS_DATA.length}
      />

      {/* Main Content Workspace */}
      <main className="flex-1 max-w-7xl w-full mx-auto px-3 sm:px-6 lg:px-8 py-4 sm:py-6 pb-24 md:pb-10">
        {/* ================= 1. SIMULATION TAB ================= */}
        {activeTab === 'simulation' && (
          <div className="space-y-6">
            {/* Context Headline */}
            <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 border-b border-slate-800/80 pb-3">
              <div>
                <h1 className="text-xl sm:text-2xl font-bold tracking-tight text-slate-100">
                  Автомашины хөдөлгүүрийн тосолгооны интерактив симуляци
                </h1>
                <p className="text-xs text-slate-400 mt-0.5">
                  Тосны хаалттай эргэлт, даралтат магистраль, шүүр, насос болон эд ангиудын тосолгоог бодит цагт ажиглаарай.
                </p>
              </div>

              {/* Quick links to theory */}
              <button
                onClick={() => setActiveTab('lessons')}
                className="text-xs text-amber-400 hover:text-amber-300 font-medium flex items-center gap-1 self-start sm:self-center"
              >
                <BookOpen className="w-3.5 h-3.5" />
                Онолын хичээл рүү очих →
              </button>
            </div>

            {/* Interactive Engine SVG Diagram */}
            <EngineSimulationCanvas
              state={simulationState}
              onSelectComponent={(comp) => setSelectedComponent(comp)}
              selectedComponentId={selectedComponent?.id || null}
              onToggleRunning={() => setIsRunning(!isRunning)}
            />

            {/* Parameters Control Deck */}
            <ControlDeck
              state={simulationState}
              onChangeRpm={setRpm}
              onChangeTemperature={setTemperature}
              onChangeOilGrade={setOilGrade}
              onChangeFilterClogged={setFilterClogged}
              onChangeOilLevel={setOilLevel}
              onApplyPreset={handleApplyPreset}
            />
          </div>
        )}

        {/* ================= 2. THEORY LESSONS TAB ================= */}
        {activeTab === 'lessons' && (
          <LessonViewer
            completedChapterIds={completedChapters}
            onToggleCompleteChapter={handleToggleCompleteChapter}
            onJumpToSimulationComponent={handleJumpToSimulationComponent}
          />
        )}

        {/* ================= 3. LABS TAB ================= */}
        {activeTab === 'labs' && <LabsViewer />}

        {/* ================= 4. QUIZ TAB ================= */}
        {activeTab === 'quiz' && <QuizModal />}

        {/* ================= 5. GLOSSARY TAB ================= */}
        {activeTab === 'glossary' && <GlossaryModal />}
      </main>

      {/* Component Details Inspection Modal */}
      <ComponentDetailModal
        component={selectedComponent}
        onClose={() => setSelectedComponent(null)}
        onGoToLesson={(compId) => {
          setActiveTab('lessons');
        }}
      />

      {/* Clean quiet footer */}
      <footer className="border-t border-slate-900 bg-slate-950 py-6 mt-8 mb-16 md:mb-0 text-center text-xs text-slate-400">
        <div className="max-w-7xl mx-auto px-4 flex flex-col sm:flex-row items-center justify-between gap-3">
          <p>
            Автомашины хөдөлгүүрийн тосолгооны систем · Интерактив цахим сургалтын систем
          </p>
          <div className="flex items-center gap-4 text-[11px] text-slate-400 font-mono">
            <span>SAE J300</span>
            <span>·</span>
            <span>API SP / ILSAC GF-6</span>
            <span>·</span>
            <span>Hydrodynamic Theory</span>
          </div>
        </div>
      </footer>
    </div>
  );
}
